#!/usr/bin/env node
const chalk = require('chalk');
const clear = require('clear');
const figlet = require('figlet');
const fs = require('fs');
const YAML = require('js-yaml');

// Command line options
const argv = require('yargs/yargs')(process.argv.slice(2))
    .usage("Usage: -r <runner> -w")
    .option("r", { alias: "runner", describe: "Target Test Runner", type: "string", choices: ['playwright', 'cypress'], demandOption: false, default: "playwright" })
    .option("w", { alias: "watchFiles", describe: "Process .c2e.yaml files when added or updated", type: "boolean", demandOption: false, default: false })
    .argv;

const ROOT = '.';
const FILTER = '.c2e.yaml';
const GROUPING = ['scenes', 'user stories'];
const ACTIONS = ['actions'];
const EVALUATIONS = ['expectations'];
const WATCH_FILES = argv.watchFiles;
const TARGET_RUNNER = argv.runner;
const GROUP = { 'cypress': 'describe', 'playwright': 'test.describe' }[TARGET_RUNNER];
const TEST = { 'cypress': 'it', 'playwright': 'test' }[TARGET_RUNNER];
const LOG = { 'cypress': 'cy.log', 'playwright': 'console.log' }[TARGET_RUNNER];
const CALLBACK = { 'cypress': '() => ', 'playwright': 'async () => ' }[TARGET_RUNNER];

// MAIN
printBanner(TARGET_RUNNER);
processFilesInFolder();
if (WATCH_FILES) { watchFiles(); }

//FUNCTIONS
function printBanner(TARGET_RUNNER) {
    console.clear();
    console.log(
        chalk.greenBright(figlet.textSync('C -2-> E', { font: "ANSI Shadow", })),
        chalk.bold.italic.gray(' by the Modly community v0.0.4d')
    );
    console.log(chalk.green('C2E generates *.spec.js test files from *.c2e.yaml files located in the local folder for use with Playwright or Cypress.'));
    console.log(chalk.bold.redBright('🚨 WARNING: C2E currently overwrites *.spec.js files without warning! 🚨 '));
    console.log(chalk.bold.italic.greenBright(`Processing files ${WATCH_FILES ? `as updated` : `once in folder ${process.cwd()}`} for use with ${TARGET_RUNNER}`));
};
function watchFiles() {
    fs.watch(ROOT, (event, fileName) => {
        try {
            if (!fs.lstatSync(fileName).isDirectory()) { //[AR-124] Ignore directories
                console.log(`${fileName} file Changed`);
                processFile(fileName);
            }
            console.log(chalk.bold.italic.greenBright(`Watching files in ${process.cwd()}...`));
        }
        catch (err) {
            console.log(chalk.bold.italic.redBright(err.message));
        }
    });
};
function processFilesInFolder() {
    fs.readdirSync(ROOT).filter(fileName => { return fileName.includes(FILTER) }).map(fileName => {
        processFile(fileName);
        // [AR-94] C2E - Remove orphan spec.js files
    });
};
function processFile(fileName) {
    console.log('Processing => ', fileName);
    let { version, capability, storyboards } = YAML.load(fs.readFileSync(fileName, 'utf8')); //load file to object & get capability variables
    Object.entries(storyboards).map(([storyboardName, storyboardObject]) => {
        processStoryboard(version, capability, storyboardName, storyboardObject);
    });
    console.log('Processing Complete for => ', fileName, ' at ', new Date().toLocaleTimeString());
};
function processStoryboard(version, capability, storyboardName, storyboardObject) {
    const avjHelpers = `
// Helpers for Object validation
import Ajv from "ajv";
const ajv = new Ajv({ $data: true, allErrors: true, allowMatchingProperties: true, });
import addFormats from "ajv-formats";
addFormats(ajv);
require("ajv-merge-patch")(ajv);
ajv.addKeyword("$version");
function validateObject(objectToValidate, schema) {
    const testOutcome = ajv.validate(schema.$id, objectToValidate);
    expect(objectToValidate).to.equal(testOutcome ? objectToValidate : ajv.errors.filter(e => e.keyword != "$merge"));
    return JSON.stringify(objectToValidate) + (testOutcome ? ' complies with ' : ' DOES NOT COMPLY WITH ') + JSON.stringify(schema);
}`;
    const playwrightHelpers = `// @js-check
import { test } from '@playwright/test';
import { expect, config } from 'chai';
config.truncateThreshold = 0;
`;
    let outputFolder = "./" + version + "/" + capability;
    if (!fs.existsSync(outputFolder)) { fs.mkdirSync(outputFolder, { recursive: true }); };
    let fileName = `${version}-${capability}-${storyboardName}.${TARGET_RUNNER}.spec.js`
    let fileContent = `
${(TARGET_RUNNER == 'playwright') ? `${playwrightHelpers}` : ``}
// Test file generated by C2E https://community.modlycrew/c2e for use with ${TARGET_RUNNER}
${avjHelpers}

// Hoisted Imports
${getImports(storyboardObject)}
// Hoisted Variables
${getVariables(storyboardObject)}
// Tests
${GROUP}("🏢 ${version} - ${capability} - ${storyboardName} ",()=>{
     ${getCode(storyboardObject)}
});`;
    console.log(`Writing => ${fileName}`);
    fs.writeFileSync(outputFolder + "/" + fileName, fileContent);
};
function cleanCode(codeBlock) {
    let cleanedCode = codeBlock.replace(/\/\/|!|js?\r?\n|\r|;$/gm, '');
    if (TARGET_RUNNER != 'cypress') { cleanedCode = cleanedCode.replace('cy.log', 'console.log') };
    return cleanedCode;
};
function getImports(storyboardObject) {
    let outputImports = new Set(); //to avoid duplicate imports
    crawlImports(storyboardObject);
    return [...outputImports].join(``);

    function crawlImports(storyboardObject) {
        if (storyboardObject) {
            Object.entries(storyboardObject).forEach(([key, value]) => {
                if ((typeof value) == 'string') {
                    value = cleanCode(value);
                    if ((value.split('\n')[0].split(' ')[0] === 'import') || (value.split('\n')[0].split('.')[0] === 'ajv')) { //handle import statements
                        outputImports.add(`${value.substring(0, value.lastIndexOf("\n"))};\n`);
                    };
                } else {
                    // outputImports.add(getImports(value));
                    crawlImports(value);
                };
            });
        };
    }
};
function getVariables(storyboardObject) {
    let outputVariables = new Set(); //to avoid duplicate declarations
    crawlVariables(storyboardObject);
    return [...outputVariables].join(``);

    function crawlVariables(storyboardObject) {
        if (storyboardObject) {
            Object.entries(storyboardObject).forEach(([key, value]) => {
                if ((typeof value) == 'string') {
                    value = cleanCode(value);
                    if (!(value.split('\n')[0].split(' ')[0] === 'import') &&
                        !(value.split('\n')[0].split('.')[0] === 'ajv') &&
                        !(value.split('\n')[0].split('.')[0] === 'cy') &&
                        !(value.split('\n')[0].split('.')[0] === 'document') &&
                        !(value.split('\n')[0].split('.')[0] === 'console') &&
                        !(value.split('\n')[0].split('(')[0] === 'expect') &&
                        !(value.split('\n')[0].split('(')[0] === 'validateObject')) {
                        outputVariables.add(`let ${value.split('\n')[0].split(' =')[0].trim()};\n`);
                    }
                } else {
                    // outputVariables.add(getVariables(value));
                    crawlVariables(value);
                };
            });
        };
    }
};
function getCode(storyboardObject) {
    let outputCode = [];
    if (storyboardObject) {
        Object.entries(storyboardObject).forEach(([key, value]) => {
            if (ACTIONS.includes(key) || EVALUATIONS.includes(key)) { // Load Code Block
                let icon = { "expectations": "🚧", "actions": "🔧" }[key];
                outputCode.push(`
    ${GROUP}("${icon} ${key}", ${CALLBACK}{
        ${getCodeBlock(key, value)}
    }); `
                );
            } else if (GROUPING.includes(key)) { // Load next Grouping
                let icon = { "storyboards": "📑", "scenes": "📃", "user stories": "👩‍🏭", }[key];
                outputCode.push(`
    ${GROUP}("${icon} ${key}", ${CALLBACK}{
        ${getCode(value)}
    });`
                );
            } else {
                outputCode.push(`
    ${GROUP}("${key.charAt(0).toUpperCase() + key.slice(1)}: ", ${CALLBACK}{
        ${getCode(value)}
    });`
                );
            }
        });
    };
    return outputCode.join(``).replace(/^\s*[\r\n]/gm, '');
};
function getCodeBlock(key, value) {
    let outputCodeBlock = [];
    if (value) {
        Object.entries(value).forEach(([key, value]) => {
            let codeBlock = (value) ? cleanCode(value) : ``;
            if (!value) {
                outputCodeBlock.push(`
    ${TEST}("🚧 ${key}", ${CALLBACK}{
        ${LOG}("${key.charAt(0).toUpperCase() + key.slice(1, 0)} code pending");
    });`); //Provide comment for empty code block
            } else if ((codeBlock.split('\n')[0].split('(')[0] === 'expect')) {
                outputCodeBlock.push(`
    ${TEST}("🚧 ${key}", ${CALLBACK}{
        ${codeBlock.replace(').', `,"${value[0]}").`)}
    });`); //Hydrate test with code description
            } else { //if (codeType == 'actions') {
                if ((codeBlock.split('\n')[0].split(' ')[0] === 'import') || (codeBlock.split('\n')[0].split('.')[0] === 'ajv')) { //handle import statements
                    outputCodeBlock.push(`
    ${TEST}("🔧 ${key}", ${CALLBACK}{
        ${LOG}(\`${codeBlock.replace(`\"`, `\'`).replace(`\n`, ``)} hoisted to Imports\`);
    });`);
                } else if ((codeBlock.split('\n')[0].split('.')[0] === 'cy') || (codeBlock.split('\n')[0].split('.')[0] === 'document') || (codeBlock.split('\n')[0].split('.')[0] === 'console')) {  //handle utility code blocks
                    outputCodeBlock.push(`
    ${TEST}("🔧 ${key}", ${CALLBACK}{
        ${codeBlock}
    });`);
                } else { //handle variable assignment & await code blocks
                    const awaitVariable = Boolean((codeBlock.split('\n')[0].split(' ')[0] != "await")); // True if promise result is to be assigned to a variable; False if simply an await call is to be executed
                    const actionVariable = codeBlock.split('\n')[0].split(' =')[0];
                    outputCodeBlock.push(`
    ${TEST}("🔧 ${key}", ${CALLBACK}{
        ${(codeBlock.includes(" = await ") && (TARGET_RUNNER == 'cypress')) ? `
        cy.wrap(null).then(() => {
            return (new Cypress.Promise((resolve, reject) => { resolve(
                ${awaitVariable ? codeBlock.split(' = await ')[1] : codeBlock.split('await ')[1]}
            )}))${awaitVariable ? `.then((obj) => { ${actionVariable} = obj })` : ``}
        })` : `
        ${codeBlock}`}
        ${LOG}("${actionVariable} => " + ${actionVariable.includes('validateObject') ? actionVariable : "JSON.stringify(" + actionVariable + ")"})
    });`);
                }
            }
        });
    };
    return outputCodeBlock.join(``);
};
