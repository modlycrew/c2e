#!/usr/bin/env node
//#region IMPORTS
const chalk = require('chalk');
const clear = require('clear');
const figlet = require('figlet');
const fs = require('fs');
const YAML = require('js-yaml');
//#endregion

const ROOT = '.';
const FILTER = '.c2e.yaml';
const GROUPING = ['scenes', 'user stories'];
const ACTIONS = ['actions'];
const EVALUATIONS = ['expectations'];

// MAIN
printBanner();
processFiles();
fs.watch(ROOT, (event, fileName) => {
    try {
        if (!fs.lstatSync(fileName).isDirectory()) {  //[AR-124] Ignore directories
            console.log(`${fileName} file Changed`);
            saveOutputFiles(loadInputFile(fileName));
        }
    }
    catch (err) {
        console.log(chalk.bold.italic.redBright(err.message));
    }
});

//#region FUNCTIONS
function printBanner() {
    console.clear();
    console.log(
        chalk.greenBright(figlet.textSync('C -2-> E', { font: "ANSI Shadow", })),
        chalk.bold.italic.gray(' by the Modly community v0.0.3c')
    );
    console.log(chalk.green('C2E generates Mocha/Chai *.spec.js test files from *.c2e.json files located in the local folder.'));
    console.log(chalk.bold.redBright('🚨 WARNING: C2E currently overwrites *.spec.js files without warning! 🚨 '));
};
function processFiles() {
    fs
        .readdirSync(ROOT)
        .filter(fileName => { return fileName.includes(FILTER) })
        .map(fileName => {
            saveOutputFiles(loadInputFile(fileName));
            // [AR-94] C2E - Remove orphan spec.js files
        });
};
function loadInputFile(fileName) {
    console.log('Processing => ', fileName);
    return YAML.load(fs.readFileSync(fileName, 'utf8'));
};
function saveOutputFiles(inputFileContent) {
    // [AR-93] C2E - Add /summary/v0.0.0.spec.js files
    // Create output folder /{$version}/{$capability}/
    let outputFolder = "./" + inputFileContent.version + "/" + inputFileContent.capability;
    if (!fs.existsSync(outputFolder)) { fs.mkdirSync(outputFolder, { recursive: true }); };
    Object.entries(inputFileContent.storyboards).map(([storyboardKey, storyboardValue]) => {
        global.outputImports = new Set();
        global.outputVariables = new Set();
        let outputFileName = inputFileContent.version + " - " + inputFileContent.capability + " - " + storyboardKey;
        let outputContentHeader = '// Test file generated by C2E https://community.modlycrew/c2e\n'
        let outputContentGenerated = '\ndescribe("🏢 ' + outputFileName + '",()=>{' + generateOutput(storyboardValue) + '});'
        let outputContentImports = '// Imports\n';
        global.outputImports.forEach((variable) => { outputContentImports += variable.trim() + ';\n'; });
        let outputContentVariables = '// Variables\n'
        global.outputVariables.forEach((variable) => { outputContentVariables += 'let ' + variable.trim() + ';\n'; });
        let outputContentAjv = ajvHelpers();
        if (inputFileContent.version) {
            console.log('Writing => ', outputFileName + '.spec.js');
            //Create output file /{$version}/{$capability}/{$version} - {$capability} - {$storyboard}.spec.js
            fs.writeFileSync(outputFolder + "/" + outputFileName + '.spec.js', outputContentHeader + outputContentAjv + outputContentImports + outputContentVariables + outputContentGenerated);
        };
    });
};
function generateOutput(input, type = "") {
    let output = "";
    if (input) {
        let array = Object.entries(input).map(([key, value]) => {
            if (GROUPING.includes(key)) {
                output += '\n';
                output += 'describe("' + key.charAt(0).toUpperCase() + key.slice(1) + ': ",()=>{';
                if (value) {
                    Object.entries(value).map((grouping) => {
                        output += generateGrouping(key, grouping[0], grouping[1]);
                    });
                };
                output += '});';
            };
            if (ACTIONS.includes(key)) {
                output += '\n';
                output += 'describe("' + key.charAt(0).toUpperCase() + key.slice(1) + ': ",()=>{';
                if (value) {
                    Object.entries(value).map((action) => {
                        output = generateAction(action[0], action[1]);
                    });
                };
                output += '});';
            };
            if (EVALUATIONS.includes(key)) {
                output += '\n';
                output += 'describe("' + key.charAt(0).toUpperCase() + key.slice(1) + ': ",()=>{';
                if (value) {
                    Object.entries(value).map((expectation) => {
                        output += generateExpectations(expectation[0], expectation[1]);
                    });
                };
                output += '});';
            };
        });
    }
    return output;

    function generateAction(actionKey, actionValue) {
        let outputVariables = "";
        let outputIt = "it('🔧 " + actionKey.replace(/'/g, "\"") + "',()=>{\n";
        let outputBody = "";
        actionValue = cleanActionValue(actionValue);
        if (!actionValue) {
            outputBody = 'console.log("ACTION: ' + actionKey + ' code pending");';
        } else {
            if ((actionValue.split('\n')[0].split(' ')[0] === 'import') || (actionValue.split('\n')[0].split('.')[0] === 'ajv')) {
                global.outputImports.add(actionValue.substring(0, actionValue.lastIndexOf(";")));
                outputBody += "cy.log('" + actionValue.substring(0, actionValue.lastIndexOf(";")).replace(/'/g, "\"") + " hoisted to Imports');\n";
            } else if ((actionValue.split('\n')[0].split('.')[0] === 'cy') || (actionValue.split('\n')[0].split('.')[0] === 'document') || (actionValue.split('\n')[0].split('.')[0] === 'console')) {
                outputBody += '    ' + actionValue + '\n';
            } else {
                const awaitVariable = Boolean((actionValue.split('\n')[0].split(' ')[0] != "await")); // True if promise result is to be assigned to a variable; False if simply an await call is to be executed
                const actionVariable = actionValue.split('\n')[0].split(' =')[0];
                if (actionValue.includes(" = await ")) {
                    outputBody += "cy.log('" + actionKey.replace(/'/g, "\"") + "');\n";
                    actionValue = actionValue.substring(0, actionValue.lastIndexOf(";")) + '\n';
                    outputBody += 'cy.wrap(null).then(() => {\n';
                    outputBody += '    return (new Cypress.Promise((resolve, reject) => {\n';
                    outputBody += '        resolve(\n';
                    if (awaitVariable) {
                        outputBody += '            ' + actionValue.split(' = await ')[1];
                    } else {
                        outputBody += '            ' + actionValue.split('await ')[1];
                    };
                    outputBody += '        );';
                    outputBody += '    }))';
                    if (awaitVariable) {
                        outputBody += '.then((obj) => {\n';
                        outputBody += '        ' + actionVariable + ' = obj;\n';
                        outputBody += '        cy.log("' + actionVariable + ' => " + JSON.stringify(' + actionVariable + '));\n';
                        outputBody += '    });\n';
                        outputBody += '});\n';
                    }
                } else {
                    outputBody += actionValue;
                    outputBody += "cy.log('" + actionVariable + " = ', JSON.stringify(" + actionVariable + "));\n";
                };
                if (actionVariable) {
                    global.outputVariables.add(actionVariable);
                };
            };
            output += outputIt + outputBody + '});';
            return output;
        };

        function cleanActionValue(actionValue) {
            if (actionValue) {
                actionValue = actionValue.replace(/\r?\n|\r/g, "");
                actionValue = actionValue.replace("\/\/js", "");
                actionValue = actionValue.replace("\/\/!js", "");
            } else {
                actionValue = "";
            }
            return actionValue;
        }
    }
    function generateGrouping(groupType, groupingKey, groupingValue) {
        let expectedOutput = '\n';
        expectedOutput += 'describe("'
        expectedOutput += { "storyboards": "📑", "scenes": "📃", "user stories": "👩‍🏭", }[groupType];
        expectedOutput += groupingKey;
        expectedOutput += '",()=>{';
        expectedOutput += generateOutput(groupingValue);
        expectedOutput += '});';
        return expectedOutput;
    }
    function generateExpectations(expectationKey, expectationValue) {
        let expectedOutput = '\n' + 'it("🚧 ' + expectationKey + '",()=>{';
        expectationValue = expectationValue ? expectationValue.replace(/\/\/|!|js?\r?\n|\r/g, "") : "";
        expectedOutput += expectationValue.replace(').', ',"' + expectationKey + '").');
        expectedOutput += '});';
        return expectedOutput;
    }
}

function ajvHelpers() {
    let ajvOutput = '\n\n// AJV Object Validation Methods\n';
    ajvOutput += 'import Ajv from "ajv";\n';
    ajvOutput += 'const ajv = new Ajv({ $data: true, allErrors: true, allowMatchingProperties: true, });\n';
    ajvOutput += 'import addFormats from "ajv-formats";\n';
    ajvOutput += 'addFormats(ajv);\n';
    ajvOutput += 'require("ajv-merge-patch")(ajv);\n';
    ajvOutput += 'ajv.addKeyword("$version");\n';
    ajvOutput += 'function validateObject(objectToValidate, schema) {\n';
    ajvOutput += '    expect(objectToValidate, "Schema => " + JSON.stringify(schema)).to.equal(ajv.validate(schema.$id, objectToValidate) ? objectToValidate : ajv.errors.filter(e => e.keyword != "$merge"));\n';
    ajvOutput += '}\n';
    return ajvOutput;
}
//#endregion
